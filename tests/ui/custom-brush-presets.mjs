// Actual Svelte controls and IPC receipts. Persistence and brush effects are
// verified by real backend tests, not emulated by this browser harness.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright-core');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(() => { window.commands = []; window.__PENTIMENTO_IPC__ = { postMessage: message => window.commands.push(JSON.parse(message)) }; });
    const url = process.env.PENTIMENTO_UI_URL ?? 'http://127.0.0.1:5187';
    await page.goto(url);
    await page.waitForFunction(() => window.commands.some(message => message.type === 'RequestBrushState'));
    const receive = message => page.evaluate(message => window.__PENTIMENTO_RECEIVE__(JSON.stringify(message)), message);
    const last = type => page.evaluate(type => window.commands.filter(message => message.type === type).at(-1)?.data, type);
    let catalog = { paint: [], sculpt: [], selected_paint: null, selected_sculpt: null, active: false, available: true, notice: null };
    let paint = { preset_id: 0, customized: true, color: [1, 0, 0, 1], size: 48, opacity: 0.37, hardness: 0.25, spacing: 0.4, blend_mode: 'Erase' };
    let sculpt = { tool: 'Crease', radius: 1.2, strength: 0.21, hardness: 0.4, falloff: 'Sharp', autosmooth: 0.17 };
    const savedReceipt = () => receive({ type: 'SavedBrushPresetsChanged', data: catalog });
    const paintReceipt = () => receive({ type: 'PaintBrushStateChanged', data: { settings: paint, presets: [{ id: 0, name: 'Hard Round' }, { id: 1, name: 'Soft Round' }], can_undo: false, can_redo: false, source_visible: true } });
    const sculptReceipt = () => receive({ type: 'SculptBrushStateChanged', data: { settings: sculpt } });
    await savedReceipt(); await paintReceipt();
    await receive({ type: 'EditModeChanged', data: { mode: 'Paint' } });
    const savePaint = page.getByRole('button', { name: 'Save paint brush', exact: true });
    assert.equal(await savePaint.isDisabled(), true);
    await page.getByLabel('Paint preset name', { exact: true }).fill(' My paint ');
    await savePaint.click(); assert.deepEqual(await last('PaintCommand'), { SaveBrushPreset: { name: 'My paint' } });
    catalog.paint = [{ id: 1, name: 'My paint' }, { id: 2, name: 'Same settings' }];
    catalog.selected_paint = 1; await savedReceipt();
    const paintChoice = page.getByLabel('Saved paint brushes', { exact: true });
    await paintChoice.selectOption('2');
    await page.getByRole('button', { name: 'Use paint brush', exact: true }).click();
    assert.deepEqual(await last('PaintCommand'), { SelectSavedBrushPreset: { preset_id: 2 } });
    assert.equal(await page.getByText('Current saved brush: Same settings', { exact: true }).count(), 0);
    catalog.selected_paint = 2; await savedReceipt();
    await page.getByText('Current saved brush: Same settings', { exact: true }).waitFor();
    assert.equal(await paintChoice.inputValue(), '2');
    assert.equal(await page.getByRole('spinbutton', { name: 'Radius value', exact: true }).inputValue(), '24');
    assert.equal(await page.getByRole('button', { name: 'Eraser', exact: true }).getAttribute('aria-pressed'), 'true');
    // Stale enabled builtin selection is refused when native ownership starts.
    await page.getByLabel('Brush preset', { exact: true }).selectOption('1');
    assert.deepEqual(await last('PaintCommand'), { SelectBrushPreset: { preset_id: 1 } });
    catalog.active = true; await savedReceipt(); await paintReceipt();
    assert.equal(await page.getByLabel('Brush preset', { exact: true }).inputValue(), '-1');
    assert.equal(await page.getByLabel('Brush preset', { exact: true }).isDisabled(), true);
    assert.equal(await savePaint.isDisabled(), true);
    assert.equal(await paintChoice.isDisabled(), true);
    catalog.active = false; await savedReceipt();
    const output = process.env.PENTIMENTO_EVIDENCE_DIR ?? '/tmp/pentimento-custom-preset-evidence';
    await mkdir(output, { recursive: true });
    await page.locator('.saved-presets').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${output}/saved-paint-presets.jpg`, type: 'jpeg', quality: 85 });
    await sculptReceipt(); await receive({ type: 'EditModeChanged', data: { mode: 'Sculpt' } });
    const sculptChoice = page.getByLabel('Saved sculpt brushes', { exact: true });
    assert.equal(await sculptChoice.locator('option').count(), 1, 'paint presets never leak into sculpt');
    await page.getByLabel('Sculpt preset name', { exact: true }).fill('Gentle crease');
    await page.getByRole('button', { name: 'Save sculpt brush', exact: true }).click();
    assert.deepEqual(await last('SculptCommand'), { SaveBrushPreset: { name: 'Gentle crease' } });
    catalog.sculpt = [{ id: 1, name: 'Gentle crease' }, { id: 2, name: 'Other name' }];
    catalog.selected_sculpt = 1; await savedReceipt();
    await sculptChoice.selectOption('2');
    await page.getByRole('button', { name: 'Use sculpt brush', exact: true }).click();
    assert.deepEqual(await last('SculptCommand'), { SelectSavedBrushPreset: { preset_id: 2 } });
    catalog.selected_sculpt = 2; await savedReceipt(); await sculptReceipt();
    await page.getByText('Current saved brush: Other name', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Crease', exact: true }).getAttribute('aria-pressed'), 'true');
    assert.equal(await page.getByRole('spinbutton', { name: 'Auto smoothing value', exact: true }).inputValue(), '17');
    await sculptChoice.selectOption('1');
    catalog.active = true; await savedReceipt();
    assert.equal(await sculptChoice.inputValue(), '2');
    for (const name of ['Save sculpt brush', 'Use sculpt brush']) assert.equal(await page.getByRole('button', { name, exact: true }).isDisabled(), true);
    catalog.active = false; await savedReceipt();
    // A reload fetches the native catalog again; this harness has no preset store.
    await page.reload(); await page.waitForFunction(() => window.commands.some(message => message.type === 'RequestBrushState'));
    await savedReceipt(); await sculptReceipt(); await receive({ type: 'EditModeChanged', data: { mode: 'Sculpt' } });
    assert.equal(await page.getByLabel('Saved sculpt brushes', { exact: true }).inputValue(), '2');
    await page.getByText('Current saved brush: Other name', { exact: true }).waitFor();
    await page.locator('.saved-presets').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${output}/saved-sculpt-presets.jpg`, type: 'jpeg', quality: 85 });
    catalog.available = false; catalog.notice = 'Saved brushes changed outside this editor. Restart to load them.'; await savedReceipt();
    assert.equal(await page.getByRole('button', { name: 'Save sculpt brush', exact: true }).isDisabled(), true);
    await page.getByRole('status').filter({ hasText: 'changed outside' }).waitFor();
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ type: 'pentimento.ui.custom_presets', status: 'passed', checks: ['save-and-select-paint', 'save-and-select-sculpt', 'mode-separation', 'duplicate-parameter-identities', 'active-refusal-reconciliation', 'native-catalog-after-reload', 'storage-error-visible'], renderer_qualification: false }));
} finally { await browser.close(); }
